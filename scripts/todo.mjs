// node scripts/todo.mjs — regenerates TODO_FILL.md from every [FILL], [DECIDE] and [PLACEHOLDER] in the repo.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const skip = /node_modules|dist|\.git|TODO_FILL|METER_ON_CONTEXT|PLAN\.md|todo\.mjs/
const files = []
const walk = (d) => readdirSync(d).forEach((f) => {
  const p = join(d, f)
  if (skip.test(p)) return
  if (statSync(p).isDirectory()) walk(p)
  else if (/\.(ts|tsx|json|md|css|html)$/.test(f)) files.push(p)
})
walk(root)

const groups = { FILL: [], DECIDE: [], PLACEHOLDER: [] }
for (const f of files) {
  readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
    for (const m of line.matchAll(/\[(FILL|DECIDE|PLACEHOLDER)\b/g)) {
      const where = relative(root, f).split('\\').join('/')
      groups[m[1]].push(`- \`${where}:${i + 1}\` — ${line.trim().slice(0, 160).split('|').join('/')}`)
    }
  })
}
const out = [
  '# TODO_FILL',
  '',
  'Generated by `npm run todo`. Re-run after editing content.',
  '',
  '- **[FILL]** must come from your real life. Nothing here was invented.',
  '- **[DECIDE]** is an open choice; the current default is in place.',
  '- **[PLACEHOLDER]** is a draft line to rewrite in your own words before recording.',
  '',
  ...Object.entries(groups).map(([k, v]) => `## [${k}] (${new Set(v).size})\n\n${[...new Set(v)].join('\n')}\n`),
].join('\n')
writeFileSync(join(root, 'TODO_FILL.md'), out)
